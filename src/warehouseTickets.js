import { prepareUsageItems } from './usageTickets.js';

export const getWarehouseAssets = (assets = []) => assets.filter((asset) => asset.status === 'Trong kho');
export const prepareWarehouseItems = (groups, assets, categories) => prepareUsageItems(groups, getWarehouseAssets(assets), categories);

export function filterWarehouseTickets(tickets, type, query = '', status = '') {
  const text = query.trim().toLowerCase();
  return (tickets || [])
    .filter((ticket) => ticket.type === type && (!status || ticket.status === status)
      && `${ticket.id} ${ticket.asset} ${ticket.requester} ${ticket.department} ${ticket.createdBy || ''} ${getTicketLineItems(ticket).map((item) => `${item.name || ''} ${item.assetId || ''} ${item.barcode || ''} ${item.categoryName || ''}`).join(' ')}`.toLowerCase().includes(text))
    .sort((a, b) => (b.createdAt || '').localeCompare(a.createdAt || '') || b.id.localeCompare(a.id));
}

export function getTicketLineItems(ticket) {
  const details = ticket.details || {};
  if (Array.isArray(details.importItems)) {
    return details.importItems.flatMap((group) => (group.items || []).map((item) => ({
      ...item, name: item.name || group.categoryName || group.categoryId, quantity: 1,
      categoryId: group.categoryId, categoryName: group.categoryName,
    })));
  }
  if (Array.isArray(details.lineItems)) return details.lineItems;
  return ticket.asset ? [{ name: ticket.asset }] : [];
}

export function getTicketGroups(ticket, assets = [], categories = []) {
  const groups = new Map();
  for (const item of getTicketLineItems(ticket)) {
    const asset = assets.find((asset) => asset.id === item.assetId);
    const categoryId = item.categoryId || asset?.categoryId || '';
    const categoryName = item.categoryName || categories.find((category) => category.id === categoryId)?.name || asset?.category || 'Chưa phân loại';
    const key = categoryId || categoryName;
    const group = groups.get(key) || { key, categoryId, categoryName, quantity: 0, items: [] };
    const quantity = Number(item.quantity) || 1;
    group.items.push({ ...item, name: item.name || asset?.name, barcode: item.barcode || asset?.barcode || '', quantity });
    group.quantity += quantity;
    groups.set(key, group);
  }
  return [...groups.values()];
}

let importSequence = 0;
export const createImportItem = () => ({ key: `item-${Date.now()}-${++importSequence}`, name: '', assetId: '', barcode: '' });
export const createImportGroup = () => ({ id: `group-${Date.now()}-${++importSequence}`, categoryId: '', items: [] });

export function prepareImportGroups(groups, categories) {
  return groups.filter((group) => group.categoryId && group.items.length).map((group) => {
    const categoryName = categories.find((category) => category.id === group.categoryId)?.name || group.categoryName || group.categoryId;
    return {
      ...group, categoryName, quantity: group.items.length,
      items: group.items.map((item, index) => {
        const assetId = item.assetId?.trim() || `AUTO-${(item.key || createImportItem().key).replace('item-', '')}`;
        return {
          ...item, assetId, name: item.name?.trim() || `${categoryName} ${index + 1}`,
          barcode: item.barcode?.trim() || `BC-${assetId.replace(/[^A-Z0-9]/gi, '').toUpperCase()}`,
          autoGenerated: !item.assetId?.trim() || item.autoGenerated === true,
          barcodeAutoGenerated: !item.barcode?.trim() || item.barcodeAutoGenerated === true,
        };
      }),
    };
  });
}
